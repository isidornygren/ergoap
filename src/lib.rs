/// Schedule for collecting sensor values from world components.
///
/// This schedule runs after [`FixedUpdate`] and before [`Planning`] in the fixed timestep.
/// Systems in this schedule should update [`SensorState`] components based on world observations.
#[derive(ScheduleLabel, Debug, Clone, PartialEq, Eq, Hash)]
pub struct SensorUpdate;

/// Schedule for generating action plans to achieve goals.
///
/// This schedule runs after [`SensorUpdate`] in the fixed timestep.
/// The planner uses A* pathfinding to find optimal action sequences based on current sensor state.
#[derive(ScheduleLabel, Debug, Clone, PartialEq, Eq, Hash)]
pub struct Planning;

/// Main plugin for the utility-goap framework.
///
/// This plugin sets up the necessary schedules and systems for GOAP planning.
/// Add this to your Bevy app to enable utility-based goal-oriented action planning.
///
/// # Schedules Added
///
/// - [`SensorUpdate`]: Collects sensor values (runs after `FixedUpdate`)
/// - [`Planning`]: Generates action plans (runs after `SensorUpdate`)
///
/// # Systems Added
///
/// - Sensor value collection system (in [`Planning`])
/// - Plan generation system (in [`Planning`])
/// - Trait type registration system (in [`First`])
/// - Target completion system (in `FixedPostUpdate`, with `target` feature)
///
/// # Example
///
/// ```
/// use bevy::prelude::*;
/// use utility_goap::UtilityGoapPlugin;
///
/// App::new()
///     .add_plugins(UtilityGoapPlugin);
/// ```
pub struct UtilityGoapPlugin;

impl Plugin for UtilityGoapPlugin {
    fn build(&self, app: &mut App) {
        app.init_schedule(SensorUpdate).init_schedule(Planning);
        {
            let mut main_schedule_order = app.world_mut().resource_mut::<FixedMainScheduleOrder>();
            main_schedule_order.insert_after(FixedUpdate, SensorUpdate);
            main_schedule_order.insert_after(SensorUpdate, Planning);
        }
        app.add_systems(Planning, (collect_sensor_values, make_plan).chain())
            .add_systems(First, |world: &mut World| register_trait_types(world));
        #[cfg(feature = "target")]
        app.add_systems(FixedPostUpdate, finish_goto);
    }
}
