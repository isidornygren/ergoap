//! # Utility GOAP
//!
//! A Goal-Oriented Action Planning (GOAP) library with utility-based scoring for the Bevy game engine.
//!
//! This crate provides a flexible framework for AI decision-making that combines GOAP planning
//! with utility-based scoring to help entities dynamically select and execute actions to achieve goals.
//!
//! ## Features
//!
//! - **GOAP Planning**: Automatic action planning using A* pathfinding to find optimal action sequences
//! - **Utility Scoring**: Score and prioritize goals based on current world state (with `utility` feature)
//! - **Target System**: Support for movement and targeting mechanics (with `target` feature)
//! - **Bevy Integration**: Seamless integration with Bevy's ECS and scheduling systems
//! - **Automatic Registration**: Trait-based component registration for sensors and actions
//!
//! ## Core Concepts
//!
//! - **Sensors**: Components that observe the world state and provide values for planning
//! - **Actions**: Discrete behaviors with preconditions and effects on the world state
//! - **Goals**: Desired world states that the planner tries to achieve
//! - **Plans**: Sequences of actions generated by the A* planner to satisfy goals
//!
//! ## Quick Start
//!
//! ```ignore
//! use bevy::prelude::*;
//! use utility_goap::prelude::*;
//!
//! fn main() {
//!     App::new()
//!         .add_plugins(UtilityGoapPlugin)
//!         .run();
//! }
//! ```
//!
//! ## Schedules
//!
//! The plugin adds two custom schedules that run during the fixed timestep:
//! - [`SensorUpdate`]: Collects sensor values from the world
//! - [`Planning`]: Generates action plans based on current sensor state and goals

